// Shared helpers for the npm packages of the Rust `clover` CLI.
//
// `build-npm.mjs` writes the per-platform packages under `npm/` and
// `publish-npm.mjs` uploads them. The root manifest deliberately does not list
// the platform packages as optionalDependencies: it is a pnpm workspace member,
// and those packages only exist after a build, so they are injected into the
// manifest for the duration of the publish instead.

import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PACKAGE_PREFIX = '@julyware/clover-cli';
export const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const NPM_DIR = join(PACKAGE_DIR, 'npm');
export const ROOT_MANIFEST_PATH = join(PACKAGE_DIR, 'package.json');
export const SEMVER_PATTERN = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;

export function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

/// Platform packages generated by `build-npm.mjs`. Empty until the first build.
export function listPlatformPackages() {
  if (!existsSync(NPM_DIR)) {
    return [];
  }

  const packages = [];
  for (const entry of readdirSync(NPM_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = join(NPM_DIR, entry.name);
    const manifestPath = join(dir, 'package.json');
    if (!existsSync(manifestPath)) continue;
    packages.push({ id: entry.name, dir, manifestPath, manifest: readJson(manifestPath) });
  }
  return packages.sort((left, right) => left.id.localeCompare(right.id));
}